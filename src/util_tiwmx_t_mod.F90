SUBROUTINE SAVE_TIWMX_T (SELF, KLUN)

IMPLICIT NONE
TYPE (TIWMX_T), INTENT (IN), TARGET :: SELF
INTEGER, INTENT (IN) :: KLUN

WRITE (KLUN) SELF%ESTABW
WRITE (KLUN) SELF%DESTABW
WRITE (KLUN) SELF%ESTABI
WRITE (KLUN) SELF%DESTABI
WRITE (KLUN) SELF%A2TAB
WRITE (KLUN) SELF%BB3TAB
WRITE (KLUN) SELF%AM3TAB
WRITE (KLUN) SELF%AF3TAB
WRITE (KLUN) SELF%A2WTAB
WRITE (KLUN) SELF%BB3WTAB
WRITE (KLUN) SELF%REDINTAB
END SUBROUTINE

SUBROUTINE LOAD_TIWMX_T (SELF, KLUN)

IMPLICIT NONE
