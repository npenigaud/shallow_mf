FUNCTION SIZE_TIWMX_T (SELF, CDPATH, LDPRINT) RESULT (KSIZE)

IMPLICIT NONE
TYPE (TIWMX_T),     INTENT (IN), TARGET :: SELF
CHARACTER(LEN=*), INTENT (IN), OPTIONAL :: CDPATH
LOGICAL,          INTENT (IN), OPTIONAL :: LDPRINT
INTEGER*8 :: KSIZE
INTEGER*8 :: ISIZE, JSIZE
LOGICAL :: LLPRINT
CHARACTER(LEN=128) :: CLPATH

LLPRINT = .FALSE.
IF (PRESENT (LDPRINT)) THEN
  LLPRINT = LDPRINT
ENDIF
CLPATH=''
IF (PRESENT (CDPATH)) THEN
  CLPATH = CDPATH
ENDIF
KSIZE = 0
ISIZE = KIND (SELF%ESTABW) * SIZE (SELF%ESTABW)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%ESTABW'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%DESTABW) * SIZE (SELF%DESTABW)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%DESTABW'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%ESTABI) * SIZE (SELF%ESTABI)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%ESTABI'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%DESTABI) * SIZE (SELF%DESTABI)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%DESTABI'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%A2TAB) * SIZE (SELF%A2TAB)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%A2TAB'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%BB3TAB) * SIZE (SELF%BB3TAB)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%BB3TAB'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%AM3TAB) * SIZE (SELF%AM3TAB)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%AM3TAB'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%AF3TAB) * SIZE (SELF%AF3TAB)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%AF3TAB'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%A2WTAB) * SIZE (SELF%A2WTAB)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%A2WTAB'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%BB3WTAB) * SIZE (SELF%BB3WTAB)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%BB3WTAB'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%REDINTAB) * SIZE (SELF%REDINTAB)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%REDINTAB'
ENDIF
KSIZE = KSIZE + ISIZE
END FUNCTION

END MODULE
