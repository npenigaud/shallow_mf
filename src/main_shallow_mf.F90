#include "shallow_mf.intfb.h"

INTEGER :: JLON, JBLK
INTEGER :: ILUNCI, ILUNFI, ILUNFO, IOUT
INTEGER :: NPROMA, NGPBLKS,KLEV,KLON,KGPBLKS
