REAL(KIND=JPRB), POINTER          :: ZFLXZTHVMF (:,:,:)          
REAL(KIND=JPRB), POINTER          :: ZFLXZTHMF (:,:,:) 
REAL(KIND=JPRB), POINTER          :: ZFLXZRMF  (:,:,:)
