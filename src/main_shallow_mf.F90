REAL(KIND=JPRB), POINTER          :: ZRV_UP  (:,:,:)  
REAL(KIND=JPRB), POINTER          :: ZU_UP  (:,:,:)   
REAL(KIND=JPRB), POINTER          :: ZV_UP  (:,:,:)   
REAL(KIND=JPRB), POINTER          :: ZTKE_UP  (:,:,:)
REAL(KIND=JPRB), POINTER          :: ZRC_UP  (:,:,:)  
