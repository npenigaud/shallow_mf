ISIZE8 = 10; 
#else
ISIZE4 = 10; 
ISIZE8 = 80; 
#endif
CALL GETOPTION ("--stack-size-4", ISIZE4)
CALL GETOPTION ("--stack-size-8", ISIZE8)
NTIME = 1; CALL GETOPTION ("--times", NTIME)

CLMETHOD = 'openmp'; CALL GETOPTION ("--method", CLMETHOD)

IBLOCKLIST => NULL ()
CALL GETOPTION ("--block-list", IBLOCKLIST)

LLSAVE = CLCASE_OUT /= ''

IF (LLSAVE) THEN
  CALL XRD_MKDIR (TRIM (CLCASE_OUT))
ENDIF

CLOUT = '-'; CALL GETOPTION ("--out", CLOUT)

CALL CHECKOPTIONS
CALL LOADALL
IF (LLVERBOSE) THEN
WRITE (0, *) " NPROMA = ", NPROMA, " NGPBLKS = ", NGPBLKS, " KLEV = ", KLEV
WRITE (0, *) " ISIZE4 = ", ISIZE4, " ISIZE8 = ", ISIZE8, " NTIME = ", NTIME
ENDIF

IF (LLSAVE) THEN
  CALL SAVEIALL
ENDIF

CALL GET_TIME (TSD)

!$ACC DATA COPY ( ZZZ , ZDZZ,  ZRHODJ , ZRHODREF , ZPABSM    , ZEXNM     ,&
!$ACC& ZSFTH, ZSFRV, ZTHM, ZRM, ZUM, ZVM, ZTKEM, ZSVM, ZDUDT_MF, ZDVDT_MF,&
!$ACC& ZDTHLDT_MF, ZDRTDT_MF, ZDSVDT_MF, ZSIGMF, ZRC_MF, ZRI_MF, ZCF_MF,&
!$ACC& ZFLXZTHVMF, ZFLXZTHMF, ZFLXZRMF, ZFLXZUMF, ZFLXZVMF, ZTHL_UP, ZRT_UP,&
!$ACC& ZRV_UP, ZU_UP, ZV_UP, ZRC_UP, ZRI_UP, ZTHV_UP, ZW_UP, ZFRAC_UP, ZEMF,&
!$ACC& ZDETR, ZENTR, IKLCL, IKETL, IKCTL) IF (TRIM (CLMETHOD) == 'openaccsinglecolumn')

IF (TRIM (CLMETHOD) == 'openaccsinglecolumn') THEN
  CALL COPY (D)
  CALL COPY (DD)
  CALL COPY (CST)
  CALL COPY (NEBN)
  CALL COPY (PARAMMF)
  CALL COPY (TURBN)
  CALL COPY (CSTURB)
  CALL COPY (ICEP)
ENDIF

CALL GET_TIME (TSC)

DO ITIME = 1, NTIME

  IF (TRIM (CLMETHOD) == 'openmp') THEN

!$OMP PARALLEL DO PRIVATE (JBLK)
    DO JBLK = 1, NGPBLKS
      CALL SHALLOW_MF( &
          D, CST, NEBN, PARAMMF, TURBN, CSTURB,ICEP,            &
       &  KRR, KRRL, KRRI, KSV,                                 &
       &  ONOMIXLG,KSV_LGBEG,KSV_LGEND,                         &
       &  PTSTEP,                                               &
       &  ZDZZ(:,:,JBLK), ZZZ(:,:,JBLK),                                            &
       &  ZRHODJ(:,:,JBLK), ZRHODREF(:,:,JBLK),                                     &
       &  ZPABSM(:,:,JBLK), ZEXNM(:,:,JBLK),                                        &
       &  ZSFTH(:,JBLK),ZSFRV(:,JBLK),                                          &
       &  ZTHM(:,:,JBLK),ZRM(:,:,:,JBLK),ZUM(:,:,JBLK),&
       &  ZVM(:,:,JBLK),ZTKEM(:,:,JBLK),ZSVM(:,:,:,JBLK),                          &
       &  ZDUDT_MF(:,:,JBLK),ZDVDT_MF(:,:,JBLK),ZDTKEDT_MF(:,:,JBLK),               &
       &  ZDTHLDT_MF(:,:,JBLK),ZDRTDT_MF(:,:,JBLK),ZDSVDT_MF(:,:,:,JBLK),        &
       &  ZSIGMF(:,:,JBLK) ,ZRC_MF(:,:,JBLK),ZRI_MF(:,:,JBLK),                     &
       &  ZCF_MF(:,:,JBLK),ZHLC_HRC(:,:,JBLK),ZHLC_HCF(:,:,JBLK),               &
       &  ZHLI_HRI(:,:,JBLK),ZHLI_HCF(:,:,JBLK),                                &
       &  ZWEIGHT_MF_CLOUD(:,:,JBLK),ZFLXZTHVMF(:,:,JBLK),               &
       &  ZFLXZTHMF(:,:,JBLK),ZFLXZRMF(:,:,JBLK),ZFLXZUMF(:,:,JBLK),ZFLXZVMF(:,:,JBLK),&
       &  ZFLXZTKEMF(:,:,JBLK),ZTHL_UP(:,:,JBLK),ZRT_UP(:,:,JBLK),ZRV_UP(:,:,JBLK),&
       &  ZRC_UP(:,:,JBLK),ZRI_UP(:,:,JBLK),ZU_UP(:,:,JBLK),                  &
       &  ZV_UP(:,:,JBLK), ZTKE_UP(:,:,JBLK),ZTHV_UP(:,:,JBLK), ZW_UP(:,:,JBLK),     &
       &  ZFRAC_UP(:,:,JBLK),ZEMF(:,:,JBLK),ZDETR(:,:,JBLK),ZENTR(:,:,JBLK),        &
       &  IKLCL(:,JBLK),IKETL(:,JBLK),IKCTL(:,JBLK),PDX,PDY,                            &
       &  KBUDGETS=KBUDGETS                            )
    ENDDO

  ELSEIF (TRIM (CLMETHOD) == 'openmpsinglecolumn') THEN

    IF (ITIME==1) THEN
      YSTACK%IALIGN = 8 
      IF (ISIZE4 > 0) ALLOCATE (YSTACK%ZDATA4 (NPROMA, KLEV, ISIZE4, NGPBLKS))
      IF (ISIZE8 > 0) ALLOCATE (YSTACK%ZDATA8 (NPROMA, KLEV, ISIZE8, NGPBLKS))
    ENDIF
!$OMP PARALLEL DO PRIVATE (JBLK, JLON, YLSTACK) FIRSTPRIVATE(D) COLLAPSE(2)
    DO JBLK = 1, NGPBLKS
      DO JLON = 1,NPROMA
        D%NIJB=JLON
        D%NIJE=JLON
        D%NIB=JLON
        D%NIE=JLON
        YLSTACK%L8 = stack_l8 (YSTACK, JBLK, NGPBLKS)
        YLSTACK%U8 = stack_u8 (YSTACK, JBLK, NGPBLKS)
        YLSTACK%L4 = stack_l4 (YSTACK, JBLK, NGPBLKS)
        YLSTACK%U4 = stack_u4 (YSTACK, JBLK, NGPBLKS)
          
        CALL SHALLOW_MF_OPENACC(  D, CST, NEBN, PARAMMF, TURBN, CSTURB,ICEP,    &
       &  KRR, KRRL, KRRI, KSV,                                 &
       &  ONOMIXLG,KSV_LGBEG,KSV_LGEND,                         &
       &  PTSTEP,                                               &
       &  ZDZZ(:,:,JBLK), ZZZ(:,:,JBLK),                                            &
       &  ZRHODJ(:,:,JBLK), ZRHODREF(:,:,JBLK),                                     &
       &  ZPABSM(:,:,JBLK), ZEXNM(:,:,JBLK),                                        &
       &  ZSFTH(:,JBLK),ZSFRV(:,JBLK),                                          &
       &  ZTHM(:,:,JBLK),ZRM(:,:,:,JBLK),ZUM(:,:,JBLK),&
       &  ZVM(:,:,JBLK),ZTKEM(:,:,JBLK),ZSVM(:,:,:,JBLK),                          &
       &  ZDUDT_MF(:,:,JBLK),ZDVDT_MF(:,:,JBLK),ZDTKEDT_MF(:,:,JBLK),               &
       &  ZDTHLDT_MF(:,:,JBLK),ZDRTDT_MF(:,:,JBLK),ZDSVDT_MF(:,:,:,JBLK),        &
       &  ZSIGMF(:,:,JBLK) ,ZRC_MF(:,:,JBLK),ZRI_MF(:,:,JBLK),                     &
       &  ZCF_MF(:,:,JBLK),ZHLC_HRC(:,:,JBLK),ZHLC_HCF(:,:,JBLK),               &
       &  ZHLI_HRI(:,:,JBLK),ZHLI_HCF(:,:,JBLK),                                &
       &  ZWEIGHT_MF_CLOUD(:,:,JBLK),ZFLXZTHVMF(:,:,JBLK),               &
       &  ZFLXZTHMF(:,:,JBLK),ZFLXZRMF(:,:,JBLK),ZFLXZUMF(:,:,JBLK),ZFLXZVMF(:,:,JBLK),&
       &  ZFLXZTKEMF(:,:,JBLK),ZTHL_UP(:,:,JBLK),ZRT_UP(:,:,JBLK),ZRV_UP(:,:,JBLK),&
       &  ZRC_UP(:,:,JBLK),ZRI_UP(:,:,JBLK),ZU_UP(:,:,JBLK),                  &
       &  ZV_UP(:,:,JBLK), ZTKE_UP(:,:,JBLK),ZTHV_UP(:,:,JBLK), ZW_UP(:,:,JBLK),     &
       &  ZFRAC_UP(:,:,JBLK),ZEMF(:,:,JBLK),ZDETR(:,:,JBLK),ZENTR(:,:,JBLK),        &
       &  IKLCL(:,JBLK),IKETL(:,JBLK),IKCTL(:,JBLK),PDX,PDY,                            &
       &  KBUDGETS=KBUDGETS, YDSTACK=YLSTACK           )
      ENDDO
    
    ENDDO

  ELSEIF (TRIM (CLMETHOD) == 'openaccsinglecolumn') THEN

#ifdef __NVCOMPILER
CALL NVTXSTARTRANGE("SHALLOW_MF_OPENACC")
#endif


    IF (ITIME==1) THEN
      YSTACK%IALIGN = 8 
      ALLOCATE (YSTACK%ZDATA4 (NPROMA, KLEV, ISIZE4, NGPBLKS))
      ALLOCATE (YSTACK%ZDATA8 (NPROMA, KLEV, ISIZE8, NGPBLKS))

!$ACC ENTER DATA CREATE (YSTACK%ZDATA4)
!$ACC ENTER DATA CREATE (YSTACK%ZDATA8)

!$ACC ENTER DATA CREATE (YSTACK)
!$ACC UPDATE DEVICE (YSTACK)
!$ACC ENTER DATA ATTACH (YSTACK%ZDATA4)
!$ACC ENTER DATA ATTACH (YSTACK%ZDATA8)

    ENDIF
    
!$ACC PARALLEL LOOP GANG &
!$ACC&PRESENT (  ZZZ , ZDZZ,  ZRHODJ , ZRHODREF , ZPABSM    , ZEXNM     ,&
!$ACC& ZSFTH, ZSFRV, ZTHM, ZRM, ZUM, ZVM, ZTKEM, ZSVM, ZDUDT_MF, ZDVDT_MF,&
!$ACC& ZDTHLDT_MF, ZDRTDT_MF, ZDSVDT_MF, ZSIGMF, ZRC_MF, ZRI_MF, ZCF_MF,&
!$ACC& ZFLXZTHVMF, ZFLXZTHMF, ZFLXZRMF, ZFLXZUMF, ZFLXZVMF, ZTHL_UP, ZRT_UP,&
!$ACC& ZRV_UP, ZU_UP, ZV_UP, ZRC_UP, ZRI_UP, ZTHV_UP, ZW_UP, ZFRAC_UP, ZEMF,&
!$ACC& ZDETR, ZENTR, IKLCL, IKETL, IKCTL, D) &
!$ACC&PRIVATE (JBLK,DD) &
!$ACC&VECTOR_LENGTH (NPROMA)
   DO JBLK = 1, NGPBLKS
!$ACC LOOP VECTOR &
!$ACC&PRIVATE (JLON,DD, YLSTACK) 
    
      DO JLON = 1, NPROMA
        DD=D    
        DD%NIJB=JLON
        DD%NIJE=JLON
        DD%NIB=JLON
        DD%NIE=JLON
        YLSTACK%L8 = stack_l8 (YSTACK, JBLK, NGPBLKS)
        YLSTACK%U8 = stack_u8 (YSTACK, JBLK, NGPBLKS)
        YLSTACK%L4 = stack_l4 (YSTACK, JBLK, NGPBLKS)
        YLSTACK%U4 = stack_u4 (YSTACK, JBLK, NGPBLKS)

        CALL SHALLOW_MF_OPENACC( &
          DD, CST, NEBN, PARAMMF, TURBN, CSTURB,ICEP,            &
       &  KRR, KRRL, KRRI, KSV,                                 &
       &  ONOMIXLG,KSV_LGBEG,KSV_LGEND,                         &
       &  PTSTEP,                                               &
       &  ZDZZ(:,:,JBLK), ZZZ(:,:,JBLK),                                            &
       &  ZRHODJ(:,:,JBLK), ZRHODREF(:,:,JBLK),                                     &
       &  ZPABSM(:,:,JBLK), ZEXNM(:,:,JBLK),                                        &
       &  ZSFTH(:,JBLK),ZSFRV(:,JBLK),                                          &
       &  ZTHM(:,:,JBLK),ZRM(:,:,:,JBLK),ZUM(:,:,JBLK),&
       &  ZVM(:,:,JBLK),ZTKEM(:,:,JBLK),ZSVM(:,:,:,JBLK),                          &
       &  ZDUDT_MF(:,:,JBLK),ZDVDT_MF(:,:,JBLK),ZDTKEDT_MF(:,:,JBLK),               &
       &  ZDTHLDT_MF(:,:,JBLK),ZDRTDT_MF(:,:,JBLK),ZDSVDT_MF(:,:,:,JBLK),        &
       &  ZSIGMF(:,:,JBLK) ,ZRC_MF(:,:,JBLK),ZRI_MF(:,:,JBLK),                     &
       &  ZCF_MF(:,:,JBLK),ZHLC_HRC(:,:,JBLK),ZHLC_HCF(:,:,JBLK),               &
       &  ZHLI_HRI(:,:,JBLK),ZHLI_HCF(:,:,JBLK),                                &
       &  ZWEIGHT_MF_CLOUD(:,:,JBLK),ZFLXZTHVMF(:,:,JBLK),               &
       &  ZFLXZTHMF(:,:,JBLK),ZFLXZRMF(:,:,JBLK),ZFLXZUMF(:,:,JBLK),ZFLXZVMF(:,:,JBLK),&
       &  ZFLXZTKEMF(:,:,JBLK),ZTHL_UP(:,:,JBLK),ZRT_UP(:,:,JBLK),ZRV_UP(:,:,JBLK),&
       &  ZRC_UP(:,:,JBLK),ZRI_UP(:,:,JBLK),ZU_UP(:,:,JBLK),                  &
       &  ZV_UP(:,:,JBLK), ZTKE_UP(:,:,JBLK),ZTHV_UP(:,:,JBLK), ZW_UP(:,:,JBLK),     &
       &  ZFRAC_UP(:,:,JBLK),ZEMF(:,:,JBLK),ZDETR(:,:,JBLK),ZENTR(:,:,JBLK),        &
       &  IKLCL(:,JBLK),IKETL(:,JBLK),IKCTL(:,JBLK),PDX,PDY,                            &
       &  KBUDGETS=KBUDGETS, YDSTACK=YLSTACK           )
      ENDDO
    
    ENDDO

#ifdef __NVCOMPILER
CALL NVTXENDRANGE()
#endif

  ENDIF

ENDDO

CALL GET_TIME (TEC)

IF (TRIM (CLMETHOD) == 'openaccsinglecolumn') THEN
  CALL WIPE (D)
  CALL WIPE (CST)
  CALL WIPE (NEBN)
  CALL WIPE (PARAMMF)
  CALL WIPE (TURBN)
  CALL WIPE (CSTURB)
  CALL WIPE (ICEP)
ENDIF

!$ACC END DATA

CALL GET_TIME (TED)

ZTC = TEC - TSC
ZTD = TED - TSD

LLEXIST = .FALSE.

IF (CLOUT == '-') THEN
  IOUT = STDOUT
ELSE
  IOUT = 77
  INQUIRE (FILE=TRIM (CLOUT), EXIST=LLEXIST)
  IF (LLEXIST) THEN
    OPEN (IOUT, FILE=TRIM (CLOUT), FORM='FORMATTED', STATUS='OLD', POSITION='APPEND')
  ELSE
    OPEN (IOUT, FILE=TRIM (CLOUT), FORM='FORMATTED', STATUS='NEW')
  ENDIF
ENDIF

IF (.NOT. LLEXIST) &
WRITE (IOUT, '(A16,";",A32,";",A8,";",A8,";",A8,4(";",A20))') &
              & "CLARCH", "CLMETHOD", "NPROMA", "NGPBLKS", "NTIME", &
              & "ZTCTOT", "ZTC", "ZTDTOT", "ZTD"

WRITE (IOUT, '(A16,";",A32,";",I8,";",I8,";",I8,4(";",E20.10))') &
              & CLARCH,  TRIM (CLMETHOD), NPROMA, NGPBLKS, NTIME, &
              & ZTC, ZTC / REAL (NPROMA*NGPBLKS*NTIME, 8), &
              & ZTD, ZTD / REAL (NPROMA*NGPBLKS*NTIME, 8)

IF (IOUT /= STDOUT) THEN
  CLOSE (IOUT)
ENDIF


IF (LLDIFF) THEN
  CALL DIFFALL
ENDIF

IF (LLSAVE) THEN
  CALL SAVEOALL
ENDIF

IF (LHOOK) CALL DR_HOOK ('MAIN_SHALLOW_MF', 1, ZHOOK_HANDLE)

CONTAINS

SUBROUTINE LOADALL

